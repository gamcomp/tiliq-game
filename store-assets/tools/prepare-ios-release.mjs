import {readFile,writeFile} from 'node:fs/promises';
import {createSign} from 'node:crypto';
import path from 'node:path';
const metadata=JSON.parse(await readFile('store-assets/store-metadata.json','utf8'));
const key=process.env.APP_STORE_CONNECT_PRIVATE_KEY?.replace(/\\n/g,'\n');
const keyId=process.env.APP_STORE_CONNECT_KEY_IDENTIFIER,issuer=process.env.APP_STORE_CONNECT_ISSUER_ID;
if(!key||!keyId||!issuer)throw Error('App Store Connect credentials missing');
const enc=o=>Buffer.from(JSON.stringify(o)).toString('base64url');
const now=Math.floor(Date.now()/1000);
const unsigned=enc({alg:'ES256',kid:keyId,typ:'JWT'})+'.'+enc({iss:issuer,iat:now-5,exp:now+600,aud:'appstoreconnect-v1'});
const signer=createSign('SHA256');signer.update(unsigned);signer.end();
const token=unsigned+'.'+signer.sign({key,dsaEncoding:'ieee-p1363'}).toString('base64url');
const response=await fetch(`https://api.appstoreconnect.apple.com/v1/apps/${process.env.APP_ID}/appStoreVersions?filter%5Bplatform%5D=IOS&limit=200`,{headers:{authorization:`Bearer ${token}`}});
const result=await response.json();
if(!response.ok)throw Error(`App Store version audit failed: ${response.status} ${JSON.stringify(result.errors?.map(e=>({code:e.code,detail:e.detail})))}`);
console.log('App Store versions:',JSON.stringify(result.data.map(v=>({version:v.attributes.versionString,state:v.attributes.appStoreState,id:v.id}))));
if(process.argv.includes('--audit-only'))process.exit(0);
const compare=(a,b)=>{const aa=a.split('.').map(Number),bb=b.split('.').map(Number);for(let i=0;i<3;i++){const d=(aa[i]||0)-(bb[i]||0);if(d)return d;}return 0;};
if(result.data.some(v=>compare(v.attributes.versionString,metadata.version)>0))throw Error('A newer version exists. Do not publish this older source.');
const localizations=Object.values(metadata.locales).map(l=>({locale:l.appStoreLocale,whats_new:l.releaseNotes,description:l.fullDescription,support_url:metadata.supportUrl}));
if(localizations.length!==14)throw Error('Expected 14 release localizations');
const destination=path.join(process.env.RUNNER_TEMP||'.','tiliq-ios-release-localizations.json');
await writeFile(destination,JSON.stringify(localizations));
console.log(`Prepared ${metadata.version} with ${localizations.length} localized release notes.`);
