import fs from 'node:fs/promises';
import vm from 'node:vm';
const path='unity-ads-config.js';
let source=await fs.readFile(path,'utf8');
const context={window:{}};vm.runInNewContext(source,context);
const config=context.window.TILIQ_UNITY_ADS;
for(const key of ['gameId','rewarded','interstitial','banner']){
  if(typeof config?.ios?.[key]!=='string'||!config.ios[key].trim())throw Error('Missing iOS Unity '+key);
}
if(process.argv.includes('--check')){console.log('iOS production configuration prerequisites passed.');process.exit(0);}
config.testMode=false;
source='// App Store production artifact configuration. Generated by release CI.\nwindow.TILIQ_UNITY_ADS = '+JSON.stringify(config,null,2)+';\n';
await fs.writeFile(path,source);await fs.writeFile('www/'+path,source);
console.log('Production Unity inventory enabled in root and bundled web configuration.');
